const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const create = require('./medicine-ps2-bios');
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'rp1-medicine-ps2-'));
const root = path.join(folder, 'Ready Player One');
const cachePath = path.join(root, 'bios-cache');
const source = path.join(folder, 'RP1 Medicine', 'roms', 'ps2', 'test.bin');
const data = Buffer.from('Synthetic BIOS test fixture');
const spec = { fileName:'test.bin', md5:crypto.createHash('md5').update(data).digest('hex'), maxBytes:1024, remoteDir:'/userdata/bios/ps2' };
let remote='', installs=0;
const factory = () => create({root,cachePath,spec,execSsh:async()=>remote,installCached:async()=>{installs++;remote=spec.md5+'  /userdata/bios/ps2/test.bin';}});
const device = {access:'ssh',platform:'batocera',host:'test-machine',user:'test'};
(async()=>{
  fs.mkdirSync(path.dirname(source),{recursive:true});fs.writeFileSync(source,data);
  const helper=factory();
  assert.equal(helper.cache(),path.join(cachePath,'test.bin'));
  assert.deepEqual(fs.readFileSync(helper.cache()),data);
  await Promise.all([helper.ensure(device),helper.ensure(device)]);
  assert.equal(installs,1,'simultaneous games share BIOS setup');
  await helper.ensure(device);assert.equal(installs,1,'verified remote BIOS is retained');
  fs.unlinkSync(path.join(cachePath,'test.bin'));fs.writeFileSync(source,'corrupt');remote='';
  await assert.rejects(helper.ensure(device),/PS2 BIOS required/);assert.equal(installs,1);
  await helper.ensure({...device,platform:'recalbox'});assert.equal(installs,1);
  await helper.ensure({...device,access:'usb'});assert.equal(installs,1);
  fs.writeFileSync(source,data);
  const broken=create({root,cachePath,spec,execSsh:async()=>'',installCached:async()=>{}});
  await assert.rejects(broken.ensure(device),/machine-side PS2 BIOS failed/);
  console.log('PASS: Medicine import, checksums, automatic setup, existing BIOS, concurrency and failure handling.');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>fs.rmSync(folder,{recursive:true,force:true}));
