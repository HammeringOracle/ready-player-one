const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const appearance = fs.readFileSync(path.join(__dirname, 'appearance.js'), 'utf8');
const css = fs.readFileSync(path.join(__dirname, 'appearance.css'), 'utf8');
const page = fs.readFileSync(path.join(__dirname, 'machine-log.html'), 'utf8');
const server = fs.readFileSync(path.join(__dirname, 'server.js'), 'utf8');
const topology = fs.readFileSync(path.join(root, 'scripts', 'generate-program-topology.py'), 'utf8');

assert.match(appearance, /id="openMachineLog"/u, 'Settings must include Machine Log as a card');
assert.match(appearance, /<strong>Machine Log<\/strong>/u);
assert.match(appearance, /src="ui\/machine-log\.html"/u, 'Machine Log must open inside RP1');
assert.match(css, /\.machine-log-dialog/u);
assert.match(page, /<h1>Machine Log<\/h1>/u, 'Copied Information Station must be renamed Machine Log');
for (const feature of ['Add Record','Save','Reset']) assert.match(page, new RegExp(feature), `Machine Log must preserve ${feature}`);
assert.doesNotMatch(page, /id="newTable"/u, 'Machine Log must not show a New Table button');
assert.doesNotMatch(page, />Add Field</u, 'Machine Log must not allow adding fields');
assert.doesNotMatch(page, />Delete Table</u, 'Machine Log must not allow deleting its fixed table');
assert.doesNotMatch(page, /data-action="collapse"/u, 'Machine Log tables must always remain expanded');
assert.match(page, /\/api\/machine-log/u, 'Machine Log must persist through RP1');
assert.match(page, /Choose Console/u, 'Console records must use a dropdown');
assert.match(page, /Great","Playable","Not Playable/u, 'Compatibility must use the approved dropdown choices');
assert.match(page, /All Machines \/ Systems/u, 'Machine Log must provide one centered machine/system filter');
assert.match(page, /Vega 8","AMD Radeon 780M/u, 'Graphics must use the approved dropdown choices');
assert.match(page, /data-graphics-filter/u, 'Machine Log must provide a Graphics filter');
assert.doesNotMatch(page, /data-console-filter|data-compatibility-filter/u, 'Machine Log must not show console or compatibility filters');
assert.match(page, /data-action="save-record-add"/u, 'Machine Log must support saving and adding another record for the same machine');
assert.match(page, /seenMachines/u, 'Repeated machine names must be visually grouped instead of displayed twice');
assert.match(page, /commitOpenRecord/u, 'Top-level Save must commit an open record instead of discarding it');
assert.match(page, /data-action="toggle-rom"/u, 'ROM entry must be optional and revealed with a plus button');
assert.match(page, /labelConsoleOnlyRecord/u, 'Console-only records must be labeled with a dash in the ROM column');
assert.match(page, /scheduleAutosave/u, 'Machine Log record fields must autosave as the user types');
assert.match(server, /url\.pathname === "\/api\/machine-log"/u);
assert.match(server, /project:readMachineLogProject\(\), consoles/u, 'Machine Log API must provide every RP1 console');
assert.match(server, /"Machine \/ System Name", "Graphics", "Console", "ROM", "Compatibility", "Fixes"/u, 'Machine Log must place Graphics before Console and Fixes after Compatibility');
assert.match(page, /Vulkan — Write Color Buffers: Off → On/u, 'Fixes must offer the Vulkan Write Color Buffers repair');
assert.match(page, /Vulkan — MSAA: Auto → Disabled/u, 'Fixes must offer the Vulkan MSAA repair');
assert.match(page, /data-fixes-filter/u, 'Machine Log must provide a Fixes filter');
assert.match(page, /data-fix-option/u, 'Machine Log must allow multiple fixes on one record');
assert.match(page, /data-action="close-fixes"/u, 'Fixes dropdown must provide a Done control');
assert.match(server, /const machineLogPath = path\.join\(root, "machine-log\.json"\)/u);
assert.match(server, /"machine-log\.json"/u, 'Machine Log must be included in RP1 configuration backups');
assert.doesNotMatch(topology, /MACHINE & CONSOLE COMPATIBILITY REGISTER|Page 2|acroForm/u, 'Topology page two must be deleted from the generator');
assert.equal((topology.match(/c\.showPage\(\)/g) || []).length, 1, 'Topology generator must produce exactly one page');
console.log('Machine Log settings integration, persistent storage, backup coverage, and one-page topology checks passed.');
