const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const xml = require('./snes-cartridge-theme')('/userdata/themes/A&B/theme.xml');
const server = fs.readFileSync(path.join(__dirname, 'server.js'), 'utf8');
assert.match(xml, /A&amp;B\/theme.xml/);
assert.match(xml, /READY PLAYER ONE SNES PICTURES/);
assert.match(xml, /<customView name="RP1Pictures" inherits="grid"/);
assert.match(xml, /<imageSource>image<\/imageSource>/);
assert.doesNotMatch(xml, /\{game:image\}|<itemTemplate>/);
assert.match(xml, /<image name="gridtile\.image">/);
assert.doesNotMatch(xml, /marquee|CARTRIDGE/);
assert.equal((xml.match(/<backgroundColor>00000000<\/backgroundColor>/g) || []).length, 2);
assert.equal((xml.match(/<backgroundEdgeColor>00000000<\/backgroundEdgeColor>/g) || []).length, 2);
assert.match(xml, /<autoLayoutSelectedZoom>1\.0<\/autoLayoutSelectedZoom>/);
assert.match(xml, /<maxSize>0\.95 0\.95<\/maxSize>/);
assert.match(xml, /<margin>0\.001823 0\.003241<\/margin>/);
assert.match(xml, /<autoLayout>4 2<\/autoLayout>/);
assert.match(xml, /rp1-snes-selector\.png/);
assert.match(xml, /<cornerSize>11 11<\/cornerSize>/);
assert.match(xml, /<color>4FA9FFFF<\/color>/);
assert.match(xml, /<animateColor>F2C94CFF<\/animateColor>/);
assert.match(server, /system === "snes" \? "11 11"/);
assert.match(server, /const snesShape = .*AddArc\(24,24,11,11/);
assert.match(server, /system === "snes" \? snesShape/);
assert.match(server, /<\\\\\/padding>\\\\s\*<selectionMode>image/);
console.log('SNES picture-theme generation checks passed.');
